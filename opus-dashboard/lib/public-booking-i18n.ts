const messages = new Map(copy.map(([mk, en, sq]) => [mk, { mk, en, sq }]));

export function publicBookingText(
  source: string,
  locale: Locale,
  values: Record<string, string | number> = {},
) {
  const message = messages.get(source)?.[locale] ?? source;
  return message.replace(/\{(\w+)\}/g, (token, key: string) =>
    String(values[key] ?? token),
  );
}
